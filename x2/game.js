function Game( objApp ) {
	const objThis = this;
	const m_objApp = objApp;
	const m_nodePrompt = document.getElementById('idPrompt');
	const m_nodeGame = document.getElementById('idGame');
	const m_objRemain = m_objApp.GetRemainObject();
	const m_objText = m_objApp.GetTextObject();
	const m_objScore = m_objApp.GetScoreObject();
	const m_objMap = m_objApp.GetMapObject();
	const m_objSolvalou = m_objApp.GetSolvalouObject();
	const m_objRegHighScore = m_objApp.GetRegHighScoreObject()

	let m_nFrameCount = 0;
	let m_bShow1UP = true;
	let m_nFlyingEnemyIndex = 0;
	let m_nStartArea = 1;
	let m_nStartWait = 0;
	let m_nMissCount = 0;
	let m_bGameOver = false;
	let m_bRegHighScore = false;
	let m_bRestart = false;
	let m_nCurArea = 1;

	function showPrompt( bShow ) {
		if( bShow ) {
			m_objText.Clear( m_nodePrompt );
			m_objText.Print( m_nodePrompt, 75, 0, 'PLAYER ONE' );
			m_objText.Print( m_nodePrompt, 91, 16, 'READY!' );
			m_objText.Print( m_nodePrompt, 67, 32, 'SOLVAROU LEFT' );
			const sRemain = ('  ' + m_objRemain.GetRemain()).slice(-3);
			m_objText.Print( m_nodePrompt, 35, 33, sRemain );
			m_nodePrompt.style.visibility = 'visible';
		}
		else {
			m_objText.Clear( m_nodePrompt );
			m_nodePrompt.style.visibility = 'hidden';
		}
	}

	function showGameOver() {
		m_objText.Clear( m_nodePrompt );
		m_objText.Print( m_nodePrompt, 83, 8, 'GAME OVER' );
		m_nodePrompt.style.visibility = 'visible';
		m_bGameOver = true;
	}

	this.Initialize = function() {
		m_nFrameCount = 0;
		m_nFlyingEnemyIndex = 0;
		m_bRestart = false;

		m_objScore.Initialize();
		m_objRemain.Initialize();
		m_objRemain.Show( true );
		showPrompt( false );
		m_nStartArea = m_objApp.GetConfigObject().GetStartArea();
		m_nStartWait = 1;
		m_nCurArea = m_nStartArea;
		m_bGameOver = false;
		m_bRegHighScore = false;

		if( m_objApp.GetConfigObject().IsMouse() )
			m_nodeGame.style.cursor = 'none';
		else
			m_nodeGame.style.cursor = 'default';

		g_nExtraAreaFlag = 0;
	}

	this.End = function() {
		m_nFlyingEnemyIndex = 0;

		m_objSolvalou.Show( false );
		m_objRemain.Show( false );
		m_objScore.Show1Up( true );
		m_objMap.Delete();
		m_objApp.GetObjectManager().DeleteAllObjects();

		m_nodeGame.style.cursor = 'default';
		g_objSound.StopAll();
	}

	this.AddFlyingEnemyIndex = function( nDelta ) {
		m_nFlyingEnemyIndex += nDelta;
		while( m_nFlyingEnemyIndex > 127 ) {
			m_nFlyingEnemyIndex -= 64;
		}
		if( m_nFlyingEnemyIndex < 0 )
			m_nFlyingEnemyIndex = 0;
	}

	this.GetFlyingEnemiesByIndex = function( nInex ) {
		const nEnemyType1   = FlyingEnemyTable[nInex][0];
		const nEnemyNum1    = FlyingEnemyTable[nInex][1];
		const nEnemyOption1 = FlyingEnemyTable[nInex][2];
		const nEnemyType2   = FlyingEnemyTable[nInex][3];
		const nEnemyNum2    = FlyingEnemyTable[nInex][4];
		const nEnemyOption2 = FlyingEnemyTable[nInex][5];
		return {enemy1:nEnemyType1, num1:nEnemyNum1, opt1:nEnemyOption1,
		        enemy2:nEnemyType2, num2:nEnemyNum2, opt2:nEnemyOption2};
	}

	this.GetFlyingEnemies = function() {
		return this.GetFlyingEnemiesByIndex( m_nFlyingEnemyIndex );
	}

	this.GetFlyingEnemyIndex = function() {
		return m_nFlyingEnemyIndex;
	}

	this.ResetFlyingEnemyIndex = function() {
		m_nFlyingEnemyIndex = 0;
	}

	this.IsRestarted = function() {
		return m_bRestart;
	}

	this.Act = function( nFrame ) {
		if( (m_nFrameCount % 16) == 0 ) {
			m_bShow1UP = !m_bShow1UP;
			m_objScore.Show1Up( m_bShow1UP );
		}

		if( m_nFrameCount == 0 ) {
			m_objMap.SetStartArea( m_nStartArea );
			m_nFrameCount++;
			return;
		}
		else if( m_nFrameCount < m_nStartWait ) {
			m_nFrameCount++;
			return;
		}
		else if( m_nFrameCount == m_nStartWait ) {
			if( m_bRegHighScore ) {
				if( m_objRegHighScore.Act() ) {
					m_bRegHighScore = false;
					showGameOver();
					m_nFrameCount = 0;
					m_nStartWait = 200;
				}
				return;
			}
			if( m_bGameOver ) {
				objThis.End();
				m_objApp.SetDemoMode( true );
				return;
			}
			showPrompt( true );
			m_objSolvalou.Initialize();
			m_objSolvalou.Show( true );
			g_objSound.Play('idSndStart');
			g_objSound.SetVolume('idSndBlaster',0);
			g_objSound.SetVolume('idSndZapper',0);
			g_objSound.SetVolume('idSndBacura',0);
			g_objSound.SetVolume('idSndMiss',0);
			g_objSound.SetVolume('idSndGExp',0);
			g_objSound.SetVolume('idSndFExp',0);
			g_objSound.SetVolume('idSndExtend',0);
			g_objSound.SetVolume('idSndZakato',0);
			m_nMissCount = 0;
			m_nFrameCount++;
			return;
		}
		else if( m_nFrameCount == 200+m_nStartWait ) {
			showPrompt( false );
		}
		else if( m_nFrameCount == 400+m_nStartWait ) {
			g_objSound.Play('idSndBGM');
			g_objSound.SetVolume('idSndBlaster', g_objSound.GetInitialVolume('idSndBlaster') );
			g_objSound.SetVolume('idSndZapper', g_objSound.GetInitialVolume('idSndZapper') );
			g_objSound.SetVolume('idSndBacura', g_objSound.GetInitialVolume('idSndBacura') );
			g_objSound.SetVolume('idSndMiss', g_objSound.GetInitialVolume('idSndMiss') );
			g_objSound.SetVolume('idSndGExp', g_objSound.GetInitialVolume('idSndGExp') );
			g_objSound.SetVolume('idSndFExp', g_objSound.GetInitialVolume('idSndFExp') );
			g_objSound.SetVolume('idSndExtend', g_objSound.GetInitialVolume('idSndExtend') );
			g_objSound.SetVolume('idSndZakato', g_objSound.GetInitialVolume('idSndZakato') );
		}

		if( nFrame == 0 ) {
			m_objMap.Scroll();
			//다음 에어리어로 진행하면 재출격 플래그를 끈다
			const nCurArea = m_objMap.GetCurrentAreaNumber();
			if( nCurArea != 0 && nCurArea != m_nCurArea ) {
				m_nCurArea = nCurArea;
				m_bRestart = false;
			}
		}
		m_objApp.GetObjectManager().Move();

		if( m_nMissCount == 0 ) {
			if( !m_objSolvalou.Action(nFrame, m_nFrameCount) ) {
				m_nMissCount = 64;
				g_objSound.StopAll();
			}
		}
		if( m_nMissCount > 0 ) {
			m_nMissCount--;
			if( m_nMissCount == 0 ) {
				// 공중 캐릭터 정리
				g_App.GetObjectManager().DeleteAllObjects();
				m_objSolvalou.Show( false );

				// 재개할 에어리어 설정
				let objArea = m_objMap.GetCurrentArea();
				const nScrollPos = objArea.GetScrollPos();
				m_nStartArea = objArea.GetAreaNo();
				// 재출격 플래그
				m_bRestart = true;
				if( nScrollPos >= 182 ) {
					m_nStartArea++;
					if( m_nStartArea > 16 )
						m_nStartArea = 7;
					//다음 에어리어로 진행하면 재출격 플래그는 꺼진다
					m_bRestart = false;
				}

				m_nStartWait = 100;
				m_nFrameCount = 0;
				g_objSound.StopAll();

				if( !m_objRemain.Decrease() ) {
					if( m_objRegHighScore.IsInRank(m_objScore.GetScore()) ) {
						m_bRegHighScore = true;
						m_nStartWait = 10;
					}
					else {
						showGameOver();
						m_nStartWait = 200;
					}
					
				}
				return;
			}
		}

		m_nFrameCount++;
		if( m_nFrameCount > 2147483647 )
			m_nFrameCount = 9999;
	}
}
